import { useState } from 'react';

export default function NdaGate({ propertyName, ndaText, onAgree }) {
  const [name, setName] = useState('');
  const [declined, setDeclined] = useState(false);
  const [submitting, setSubmitting] = useState(false);
  const [error, setError] = useState(null);

  async function handleAgree() {
    if (!name.trim() || submitting) return;
    setSubmitting(true);
    setError(null);
    try {
      await onAgree(name.trim());
    } catch (err) {
      setError(err.message);
      setSubmitting(false);
    }
  }

  if (declined) {
    return (
      <div className="nda-gate-shell">
        <div className="nda-gate-card">
          <h2>Access Declined</h2>
          <p>You've chosen not to sign the agreement, so this document can't be shown. If that was a mistake, you can go back and sign below.</p>
          <button type="button" className="btn btn-ghost" onClick={() => setDeclined(false)}>
            ← Back to Agreement
          </button>
        </div>
      </div>
    );
  }

  return (
    <div className="nda-gate-shell">
      <div className="nda-gate-card">
        <h2>Confidentiality Agreement</h2>
        <p className="nda-gate-subtitle">Please review and sign before viewing {propertyName ? `the offering for ${propertyName}` : 'this offering'}.</p>

        <div className="nda-gate-disclaimer">
          This NDA was generated by AI and has not been reviewed by an attorney. Consult your legal counsel before relying on it for sensitive
          transactions.
        </div>

        <div className="nda-gate-text">{ndaText || 'No agreement text has been provided yet. Contact the broker.'}</div>

        {error && (
          <p className="field-hint" style={{ color: 'var(--danger)' }}>
            {error}
          </p>
        )}

        <div className="field">
          <label>Your Full Name</label>
          <input type="text" value={name} onChange={(e) => setName(e.target.value)} placeholder="Jane Recipient" />
        </div>

        <div style={{ display: 'flex', gap: 8, justifyContent: 'flex-end' }}>
          <button type="button" className="btn btn-ghost" onClick={() => setDeclined(true)} disabled={submitting}>
            Decline
          </button>
          <button type="button" className="btn btn-gold" onClick={handleAgree} disabled={submitting || !name.trim()}>
            {submitting ? 'Submitting…' : 'Agree & View Document'}
          </button>
        </div>
      </div>
    </div>
  );
}
